"""November recipe source fidelity, related dishes and December isolation."""
import json
from pathlib import Path
from playwright.sync_api import sync_playwright, expect
DATA=json.loads((Path(__file__).resolve().parents[1]/'menu-periods.json').read_text())
with sync_playwright() as p:
    b=p.chromium.launch(headless=True,executable_path='/usr/bin/chromium',args=['--no-sandbox'])
    page=b.new_page(viewport={'width':1280,'height':900},reduced_motion='reduce')
    page.add_init_script("localStorage.setItem('table-selectedDate',JSON.stringify('2026-11-08'))")
    errors=[];page.on('pageerror',lambda e:errors.append(str(e)))
    page.goto('http://127.0.0.1:8000');page.locator('#identity button[value=liza]').click()
    expect(page.locator('.meal').first.locator('[data-meal]')).to_have_count(0)
    page.locator('[data-tab=recipes]').click();page.locator('[data-filter=all]').click()
    expect(page.locator('.recipe-card')).to_have_count(26)
    for r in DATA['november']['recipes']:
        page.locator(f'[data-recipe="{r["id"]}"]').click()
        expect(page.locator('#recipe-content h2')).to_have_text(r['title'])
        expect(page.locator('#recipe-content .serving').first).to_contain_text(r['ingredients'])
        expect(page.locator('.recipe-portions')).to_contain_text(r['portions'])
        expect(page.locator('.recipe-steps li')).to_have_count(len(r['instructions']))
        if r['id']==4:
            page.locator('[data-related-recipe="3"]').click()
            expect(page.locator('#recipe-content h2')).to_have_text('Куриные котлеты')
            page.locator('[data-related-recipe="4"]').click()
            expect(page.locator('#recipe-content h2')).to_have_text('Куриные котлеты с картофелем')
        page.locator('#recipe-dialog .close').click()
    page.locator('#search').fill('молоко 80 мл')
    expect(page.locator('.recipe-card')).to_have_count(1)
    expect(page.locator('.recipe-card')).to_contain_text('Спиральки с курицей и сыром')
    page.locator('#search').fill('')
    page.locator('#recipe-day').fill('2026-11-11');page.locator('#recipe-day').dispatch_event('change')
    page.locator('[data-tab=menu]').click()
    page.locator('#profile').click();page.locator('#identity button[value=katya]').click()
    page.locator('[data-meal="1"]').click()
    expect(page.locator('#recipe-content h2')).to_have_text('Курица с картофельными дольками')
    page.locator('[data-related-recipe="19"]').click()
    expect(page.locator('#recipe-content h2')).to_have_text('Салат: яйцо, огурец, помидор, сыр')
    expect(page.locator('.recipe-portions')).to_contain_text('Кате к обеду, Лизе к перекусу')
    page.locator('#recipe-dialog .close').click()
    page.locator('.ribbon-day[data-day="21"]').click();page.locator('[data-meal="1"]').click()
    expect(page.locator('#recipe-content h2')).to_have_text('Куриные котлеты с картофелем')
    page.locator('[data-related-recipe="3"]').click()
    expect(page.locator('#recipe-content h2')).to_have_text('Куриные котлеты')
    expect(page.locator('#recipe-content')).to_contain_text('Куриный фарш 400 г')
    page.set_viewport_size({'width':390,'height':844})
    assert page.evaluate('document.documentElement.scrollWidth <= innerWidth')
    page.screenshot(path='/tmp/nov-recipe-source.png')
    page.locator('#recipe-dialog .close').click();page.locator('[data-tab=recipes]').click()
    page.locator('#recipe-day').fill('2026-12-01');page.locator('#recipe-day').dispatch_event('change')
    page.locator('[data-filter=all]').click()
    expect(page.locator('.recipe-card')).to_have_count(len(DATA['future']['recipes']))
    assert not errors,errors
    b.close()
    print('November recipe browser checks passed: all 26 ingredient/step/portion records, search, main+salad switching, linked cutlet base, mobile and December isolation.')
